import { useMutation, useQueryClient } from '@tanstack/react-query';
import { axiosInstance } from '@/lib/axios';

export interface CreateClientPayload {
  name: string;
  email: string;
  phone?: string;
  address?: string;
  companyName?: string;
}

export const useCreateClient = () => {
  const queryClient = useQueryClient();

  return useMutation({
    mutationFn: async (payload: CreateClientPayload) => {
      const response = await axiosInstance.post('/clients', payload);
      // DEBUG: Dekhte hain exact kya aaya
      console.log("CREATE CLIENT RAW RESPONSE:", response);
      
      const resData = response.data;
      const client = resData?.data?.client || resData?.client || resData?.data || resData;
      // One-time password generated by the server; shown to the admin once, never stored in plain text.
      return { ...client, temporaryPassword: resData?.data?.temporaryPassword as string | undefined };
    },
    onSuccess: (newClient) => {
      console.log("CLIENT CREATED SUCCESSFULLY:", newClient);
      
      // Forcefully saare clients queries ko refetch karo
      queryClient.invalidateQueries({ queryKey: ['clients'] });
    },
    onError: (error) => {
      console.error("CLIENT CREATION FAILED:", error);
    }
  });
};
